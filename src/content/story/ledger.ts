/**
 * 账本 —— 前一个你写的日志，和你自己在心里过的那份信条表。
 *
 * 这不是 UI 面板，是一个叙事装置，同时解决三个问题：
 *
 *  1. **主题**：GDD §7.1 第五层真相是"路径就是书写"。既然如此，玩家做过的每件事
 *     都必须能被读出来 —— 而且是被**别人**的字读出来。日志页上写着你今天做过的事，
 *     笔迹是你的，墨是干的。这比任何一句台词都更能说明"你不是第一个"。
 *  2. **机制**：每一条 `did.*` / `know.*` 都在这里被真正读取。校验器因此能查出
 *     "写了但没人读"的死旗标 —— 那意味着一个动作没有留下痕迹，在本作里等于 bug。
 *  3. **代价**：读一行要付一口呼吸。想知道自己是谁，就得少活一点。
 *
 * 每一行的语气（tone）决定批注落在哪一页边：
 *   obey 顺从 / refuse 拒绝 / cruel 狠 / kind 软 / curious 好奇 / count 数
 * 批注节点在 npc-yourself.ts 里（self.margin.*）—— 那是"他"对你的评价，只有六种，
 * 因为他见过的样本只有六种走法。
 */

