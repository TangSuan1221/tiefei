const PER_PAGE = 12;

function slug(flag: string): string {
  return flag.replace(/\./g, '-');
}

function pages(
  entries: readonly LedgerEntry[],
  prefix: string,
  head: string,
  headCorrupt: string,
  speaker: string | undefined,
  tail: string,
  /** 这一行什么时候出现。账册用"至少一次"，日志和信条用"做过/知道"。 */
  gate: (flag: string) => Condition = on,
): NarrativeNode[] {
  const out: NarrativeNode[] = [];
  const total = Math.ceil(entries.length / PER_PAGE);
  for (let p = 0; p < total; p++) {
    const slice = entries.slice(p * PER_PAGE, (p + 1) * PER_PAGE);
    const id = `${prefix}.p${p + 1}`;
    const nextId = p + 1 < total ? `${prefix}.p${p + 2}` : null;
    out.push({
      id,
      speaker,
      text: `${head}（第 ${p + 1} / ${total} 页）`,
      corruptedText: cor([45, `${headCorrupt}（第 ${p + 1} / ${total} 页）`]),
      tags: p === 0 ? ['entry', 'hub', 'ledger'] : ['hub', 'ledger'],
      choices: [
        ...slice.map((e) =>
          c({
            id: `${prefix}.${slug(e.flag)}`,
            label: e.line,
            cost: 1,
            requires: gate(e.flag),
            gateMode: 'hide',
            effects: [addf('count.ledger-lines-read', 1)],
            goto: MARGIN[e.tone],
          }),
        ),
        ...(nextId
          ? [
              c({
                id: `${id}.next`,
                label: '翻页。',
                cost: 1,
                effects: [addf('count.ledger-pages', 1)],
                goto: nextId,
              })
            ]
          : []),
        ...(p > 0
          ? [c({ id: `${id}.prev`, label: '翻回去。', cost: 1, goto: `${prefix}.p${p}` })]
          : []),
        c({
          id: `${id}.close`,
          label: tail,
          cost: 1,
          effects: [mark('silence', 1)],
        })
      ],
    });
  }
  return out;
}

