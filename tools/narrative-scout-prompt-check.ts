import assert from 'node:assert/strict';
import {campaign} from '../src/narrative-lab/campaign';
import {StoryEngine} from '../src/narrative-lab/engine';
import {composeScoutPrompt} from '../src/narrative-lab/prompt-composer';
import library from '../src/narrative-lab/prompt-library.json' with {type:'json'};
const engine=new StoryEngine(campaign);
assert(engine.shoot().ok);
const captured=engine.snapshot().tapes[0];
assert(!captured.ready);assert.equal(engine.snapshot().knowledge.player.length,0);
assert(captured.videoPrompt?.prompt?.includes('three long webbed fingers'));assert(captured.videoPrompt?.prompt?.includes('abyssal Lovecraftian deep-sea organism'));assert(captured.videoPrompt?.prompt?.includes('never stands, walks or crawls'));
assert(captured.videoPrompt?.prompt?.includes('Nobody is visible behind it'));
assert(!captured.videoPrompt?.prompt?.includes('dark glass visor'));
assert(captured.videoPrompt?.storyboard?.includes('看不到艾里亚斯'));
assert(!captured.videoPrompt?.prompt?.includes('不能算隔离'));
const shot=library.shots.find(s=>s.choiceId==='@scout')!;
const original=shot.subject;
shot.subject='Changed library after exposure';
engine.tick(17);
assert.deepEqual(engine.snapshot().tapes[0].videoPrompt,captured.videoPrompt);
const restored=new StoryEngine(campaign);assert(restored.restore(engine.serialize()).ok);
assert.deepEqual(restored.snapshot().tapes[0].videoPrompt,captured.videoPrompt);
shot.subject=original;
assert(engine.analyze().ok);assert(engine.act('lure-noise').ok);assert(engine.shoot().ok);engine.tick(17);
assert(engine.snapshot().tapes[1].videoPrompt?.prompt?.includes('close beside the emitting submarine'));
assert.deepEqual(engine.snapshot().tapes[0].videoPrompt,captured.videoPrompt);
const legacy=JSON.parse(engine.serialize());delete legacy.tapes[0].videoPrompt;
assert(new StoryEngine(campaign).restore(JSON.stringify(legacy)).ok);
const invalid=JSON.parse(engine.serialize());invalid.tapes[0].videoPrompt={prompt:42,note:'bad',storyboard:null};
assert.equal(new StoryEngine(campaign).restore(JSON.stringify(invalid)).ok,false);
assert.equal(composeScoutPrompt({...campaign.scenes[0],scoutFootage:'different snapshot'}).prompt,null);
assert.equal(composeScoutPrompt({...campaign.scenes[0],observation:'active-sonar'}).prompt,null);
assert.equal(composeScoutPrompt(campaign.scenes[1]).prompt,null);
console.log('PASS scout: first exposure, visibility, no early knowledge, immutable prompt through library edit / result / restore, legacy save, malformed snapshot, missing and changed shots');
