import {chromium,expect} from '@playwright/test';
import {writeFileSync} from 'node:fs';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5174/narrative.html');
await expect(page.locator('[data-story-chapter]')).toHaveCount(5);
let frame=page.frameLocator('iframe');
await expect(frame.locator('h2', {hasText:'第三章：不要靠窗'})).toBeInViewport();
await page.screenshot({path:'qa/story/narrative-tool-current.png'});
await page.locator('[data-story-chapter="1"]').click();
await expect(page.frameLocator('iframe').locator('h2').filter({hasText:'第一章'})).toBeInViewport();
await page.locator('[data-tab="story-audit"]').click();
await expect(page.locator('main')).toContainText('MET-031');
await page.locator('[data-tab="flow"]').click();
await expect(page.locator('.top-note')).toContainText('旧版');
await page.locator('[data-tab="story"]').click();
await page.locator('[data-story-chapter="3"]').click();
await page.setViewportSize({width:390,height:844});
await expect(page.frameLocator('iframe').locator('h2').filter({hasText:'第三章：不要靠窗'})).toBeInViewport();
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
expect(overflow).toBe(false);expect(errors).toEqual([]);
writeFileSync('qa/story/narrative-tool-check.json',JSON.stringify({chapterCount:5,defaultChapter:3,chapterSwitch:true,auditVisible:true,legacySeparated:true,mobileOverflow:overflow,errors},null,2));
await browser.close();
