import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
const browser=await chromium.launch({channel:'msedge',headless:true});
try {
 const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:5173/');await page.locator('[data-id="new"]').click();
 await page.waitForFunction(()=>!!window.__pod);await mkdir('qa/cabin',{recursive:true});
 await page.waitForTimeout(1800);await page.screenshot({path:'qa/cabin/window-overview.png'});
 await page.keyboard.press('4');await page.waitForTimeout(1800);
 assert.equal(await page.evaluate(()=>window.__pod.at),'camera');
 const lamp=await page.evaluate(()=>window.__pod.lamp);
 await page.mouse.click(795,686);
 assert.notEqual(await page.evaluate(()=>window.__pod.lamp),lamp,'physical lamp key toggles lamp');
 const beforeStick=await page.evaluate(()=>window.__pod.traveled);
 await page.mouse.move(375,620);await page.mouse.down();await page.mouse.move(400,550,{steps:8});
 await page.waitForFunction(d=>window.__pod.traveled>d+.3,beforeStick,{timeout:10000});
 await page.mouse.up();
 const start=await page.evaluate(()=>window.__pod.traveled);
 await page.keyboard.down('Space');
 await page.waitForFunction(d=>window.__pod.traveled>d+1,start,{timeout:15000});
 await page.keyboard.up('Space');
 assert.ok(await page.evaluate(()=>window.__pod.pilot.speed>0),'released thrust keeps inertia');
 const heading=await page.evaluate(()=>window.__pod.heading);
 await page.keyboard.down('j');await page.waitForTimeout(500);await page.keyboard.up('j');
 assert.notEqual(await page.evaluate(()=>window.__pod.heading),heading);
 assert.equal(await page.locator('#campaign-journal').count(),0,'helm J does not open journal');
 await page.keyboard.down('Shift');await page.waitForFunction(()=>window.__pod.pilot.speed<.015);await page.keyboard.up('Shift');
 await page.screenshot({path:'qa/cabin/window-controls.png'});
 await page.keyboard.press('Escape');await page.waitForTimeout(500);
 await page.keyboard.press('6');await page.waitForTimeout(1800);
 await page.screenshot({path:'qa/cabin/window-navigation.png'});
 await page.keyboard.press('Escape');await page.waitForTimeout(500);
 await page.setViewportSize({width:933,height:983});
 await page.keyboard.press('4');await page.waitForTimeout(1800);
 await page.screenshot({path:'qa/cabin/window-portrait.png'});
 assert.deepEqual(errors,[]);console.log('PASS held thrust, coasting, helm steering, braking, centered window, portrait, no page errors');
}finally{await browser.close();}
