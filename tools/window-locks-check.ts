import assert from 'node:assert/strict';
import {Box3,PerspectiveCamera,Vector3} from 'three';
import {collectWindowLocks,WindowFocus,windowRect} from '../src/pod/view/window-locks';
const camera=new PerspectiveCamera(64,1024/720,.08,120);camera.updateMatrixWorld(true);
const box=(x:number,z:number,half=.5)=>new Box3(new Vector3(x-half,-half,z-half),new Vector3(x+half,half,z+half));
const near=box(0,-3.8),far=box(0,-4),wall=new Box3(new Vector3(-3,-3,-2),new Vector3(3,3,-1.8));
const target=(bounds:Box3,enabled=true,id='box')=>({id,bounds,reach:3.4,enabled});
assert.equal(collectWindowLocks(camera,[near],[target(near)]).length,1,'3.3m surface can focus');
assert.equal(collectWindowLocks(camera,[far],[target(far)])[0].focused,false,'3.5m approach range does not grant focus');
assert.equal(collectWindowLocks(camera,[],[target(box(0,-6.3))])[0].distance,5.8,'range is optical surface distance');
assert.deepEqual(collectWindowLocks(camera,[],[target(box(0,-8.6))]),[],'beyond 8m absent');
assert.deepEqual(collectWindowLocks(camera,[near],[target(near,false)]),[],'disabled absent');
assert.deepEqual(collectWindowLocks(camera,[wall,near],[target(near)]),[],'occluded target absent, wall never marked');
assert.deepEqual(collectWindowLocks(camera,[wall],[]),[],'obstacle never marked');
assert.deepEqual(collectWindowLocks(camera,[],[target(box(3,-2))]),[],'off-axis absent');
assert.equal(windowRect(box(0,4),camera),null,'behind hidden');
const closer=box(0,-2);assert.equal(collectWindowLocks(camera,[],[target(near),target(closer,true,'closer')])[0].id,'closer','one nearest');
const focus=new WindowFocus();assert.equal(focus.update('a',100),0);assert.equal(focus.update('a',325),.5);assert.equal(focus.update('a',550),1);assert.equal(focus.update(undefined,600),0);assert.equal(focus.update('a',610),0);assert.equal(focus.update('b',1100),0);
assert.equal(focus.update('b',2000),1,'slow render does not prevent acquisition');
console.log('PASS: close centred single target; range, occlusion, disabled, obstacles; acquisition/reset');
